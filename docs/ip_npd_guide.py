def step_by_id(step_id: str) -> GuideStep | None:
    aliases = {
        "alfa": "npd_selfemp",
        "register": "other_reg",
        "npd_check": "tax",
    }
    step_id = aliases.get(step_id, step_id)
    for step in STEPS:
        if step.id == step_id:
            return step
    return None


def first_step() -> GuideStep:
    return STEPS[0]


def next_step_id(current_id: str) -> str | None:
    aliases = {"alfa": "npd_selfemp", "register": "other_reg", "npd_check": "tax"}
    current_id = aliases.get(current_id, current_id)
    if current_id in _NEXT:
        return _NEXT[current_id]
    return "why"


def registration_step_ids() -> frozenset[str]:
    """Шаги, где показываем скрин «Оставить заявку»."""
