def step_by_id(step_id: str) -> GuideStep | None:
    for step in STEPS:
        if step.id == step_id:
            return step
    return None


def first_step() -> GuideStep:
    return STEPS[0]


def next_step_id(current_id: str) -> str | None:
    ids = [s.id for s in STEPS]
    if current_id not in ids:
        return ids[0]
    idx = ids.index(current_id)
    if idx + 1 >= len(ids):
        return None
    return ids[idx + 1]


